export type HoldingKey = keyof (typeof messages)['en'];

export function th(
  lang: Language,
  key: HoldingKey,
  vars: Record<string, string | number> = {},
): string {
  return messages[lang][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    name === 'nb' ? NB : String(vars[name] ?? ''),
  );
}
