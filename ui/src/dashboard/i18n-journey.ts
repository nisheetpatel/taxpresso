export type JourneyMessageKey = keyof (typeof messages)['en'];

export function tj(
  lang: Language,
  key: JourneyMessageKey,
  vars: Record<string, string | number> = {},
): string {
  return messages[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export const isJourneyKey = (key: string): key is JourneyMessageKey => key in messages.en;
