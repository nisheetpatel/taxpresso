describe('IFD 2026', () => {
  it('reproduces every row of the official table, single and married', () => {
    for (const [income, tax] of single)
      expect(ifdScaleTax2026(income * 100, 'single'), `single ${income}`).toBe(tax);
    for (const [income, tax] of married)
      expect(ifdScaleTax2026(income * 100, 'married'), `married ${income}`).toBe(tax);
  });

  it('drops fractions under CHF 100, rounds down to 5 centimes, and skips amounts under CHF 25', () => {
    expect(ifdTax2026(2_300_099, 'single')).toBe(6005); // 60.06 on the table
    expect(ifdTax2026(1_800_000, 'single')).toBe(0); // 21.56 is under 25
    expect(ifdScaleTax2026(4_349_999, 'single')).toBe(ifdScaleTax2026(4_340_000, 'single'));
  });

  it('takes CHF 263 per child off the married and single-parent scale', () => {
    expect(ifdTax2026(10_000_000, 'married', 2)).toBe(181_600 - 2 * 26_300);
  });
});
